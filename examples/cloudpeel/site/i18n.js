let LANG = "en";

function tr(key, vars = {}) {
  const s = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}
const trRegion = (name) => REGION_TR[name]?.[LANG] ?? name;
const trPool = (label) => POOL_TR[label]?.[LANG] ?? label;

function initialLang() {
  const fromHash = new URLSearchParams(location.hash.slice(1)).get("lang");
  if (fromHash in LANGS) return fromHash;
  try {
    const saved = localStorage.getItem("cloudpeel-lang");
    if (saved in LANGS) return saved;
  } catch { /* storage may be blocked */ }
  const nav = (navigator.language || "en").toLowerCase();
  return nav.startsWith("zh") ? "zh" : nav.startsWith("nl") ? "nl" : "en";
}

// Fill every element marked with data-i18n / data-i18n-html / data-i18n-ph / data-i18n-aria.
function applyStatic() {
  document.documentElement.lang = { en: "en", zh: "zh-Hant", nl: "nl" }[LANG];
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = tr(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-html]")) el.innerHTML = tr(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll("[data-i18n-ph]")) el.placeholder = tr(el.dataset.i18nPh);
  for (const el of document.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", tr(el.dataset.i18nAria));
  for (const b of document.querySelectorAll("[data-lang]")) b.setAttribute("aria-pressed", b.dataset.lang === LANG);
}
